def candy():
    """A wrapped sweet: the candy in the middle, the wrapper twisted to a bow at each end."""
    m = Model('fx_candy', 64, 37)
    sweet, wrap = (255, 64, 120), (255, 226, 70)

    def striped(f, r, m):
        x0, y0, x1, y1 = r
        m.fill(r, sweet, 0.03)
        for y in range(y0, y1):
            for x in range(x0, x1):
                if (x + y) % 4 < 2:
                    m.put(x, y, (255, 250, 250))
    m.box([5, 6, 6], [11, 10, 10], striped)
    m.box([3, 7, 7], [5, 9, 9], solid(wrap, 0.05))
    m.box([1, 6, 6], [3, 10, 10], solid(wrap, 0.05))
    m.box([11, 7, 7], [13, 9, 9], solid(wrap, 0.05))
    m.box([13, 6, 6], [15, 10, 10], solid(wrap, 0.05))
    return m.save()


def mash_wave():
    """32 x 32, tiled round the wave: mash, lumpy, gravy pooling along the top edge."""
    rng = random.Random(29)
    im = Image.new('RGBA', (32, 32))
    px = im.load()
    for y in range(32):
        for x in range(32):
            lump = 0.92 + 0.1 * math.sin(x * 0.9 + math.sin(y * 0.7) * 2) * math.cos(y * 0.6)
            c = tone((246, 232, 196), lump + rng.uniform(-0.04, 0.04))
            if y < 5 + int(2 * math.sin(x * 0.5)):
                c = tone((150, 92, 44), 0.9 + rng.uniform(-0.08, 0.08))     # gravy
            elif rng.random() < 0.02:
                c = (255, 236, 120, 255)                                     # a lump of butter
            px[x, y] = c
    path = os.path.join(ASSETS, 'textures/entity/mash_wave.png')
    im.save(path)
    return path


