#!/usr/bin/env python3
"""Generates the 3D models of the boss fight's props, as item models (Java block-model JSON).

Writes, under src/main/resources/assets/papon/:
  models/item/<name>.json + textures/item/<name>.png   for each model below
  textures/entity/mash_wave.png                         the mashed-potato wall (MashWaveRenderer)

  tequila         the tequila (item, and the molotov in flight): a squat añejo bottle, gold tequila behind
                  clear glass, a cream label with a blue agave, a wooden ball cork under a green tax stamp
  fx_spud         a round from the potato gatling: a little russet with eyes
  fx_meteor       a baked potato from the sky (on fire: the particles): split, butter in the split
  fx_cleaver      a meat cleaver: Dungeons Delight's iron cleaver in 3D (thrown, it spins)
  fx_fry          a giant crinkle-cut fry (a javelin off his fry wings)
  fx_tot          a tater tot (the cluster bomb, and its bomblets)
  fx_guitar       the singer's requinto, thrown back to him over the boss's shoulder (phase three)
  fx_burrito      a giant burrito, a player rolled up inside (their head sticks out the top)
  fx_sprouts      a ring of potato sprouts bursting out of the ground
  fx_giant_spud   the Spud Singularity: a giant potato
  fx_pinata       La Piñata (phase three): a potato piñata in bands of fringed crepe paper, a painted grin, a
                  rope loop on top (he kicks it open over the sand)
  fx_candy        a wrapped candy bomb out of it: a bright sweet, its wrapper twisted at both ends

All are drawn by client/PropRenderer (oriented, scaled, spun). Each element's six faces are packed
onto the texture at RES pixels per model unit and painted by a function per element.
"""
import json
import math
import os
import random

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'src/main/resources/assets/papon')
RES = 2

# face -> which two axes of the box it spans (width axis, height axis)
SPAN = {'north': (0, 1), 'south': (0, 1), 'east': (2, 1), 'west': (2, 1), 'up': (0, 2), 'down': (0, 2)}


def clamp(v):
    return max(0, min(255, int(v)))


def tone(c, k, a=None):
    return (clamp(c[0] * k), clamp(c[1] * k), clamp(c[2] * k), c[3] if a is None and len(c) > 3 else (255 if a is None else a))


class Model:
    def __init__(self, name, tex=64, seed=7):
        self.name = name
        self.tex = tex
        self.im = Image.new('RGBA', (tex, tex), (0, 0, 0, 0))
        self.px = self.im.load()
        self.rng = random.Random(seed)
        self.x = self.y = self.row = 0
        self.elements = []
        self.display = {}
        self.render_type = None

    def _take(self, w, h):
        if self.x + w > self.tex:
            self.x, self.y, self.row = 0, self.y + self.row, 0
        if self.y + h > self.tex:
            raise ValueError('%s: texture full' % self.name)
        r = (self.x, self.y, self.x + w, self.y + h)
        self.x += w
        self.row = max(self.row, h)
        return r

    def box(self, frm, to, paint, rot=None, name=None, skip=()):
        """paint(face, rect, model) fills the face's pixel rect (x0, y0, x1, y1), row 0 at the face's top."""
        size = [to[i] - frm[i] for i in range(3)]
        faces = {}
        for f, (a, b) in SPAN.items():
            if f in skip:
                continue
            w = max(1, int(math.ceil(size[a] * RES)))
            h = max(1, int(math.ceil(size[b] * RES)))
            r = self._take(w, h)
            paint(f, r, self)
            k = 16.0 / self.tex
            faces[f] = {'uv': [r[0] * k, r[1] * k, r[2] * k, r[3] * k], 'texture': '#0'}
        e = {'from': list(frm), 'to': list(to), 'faces': faces}
        if name:
            e['name'] = name
        if rot:
            e['rotation'] = rot
        self.elements.append(e)

    # ---- painting helpers
    def fill(self, r, c, noise=0.06):
        x0, y0, x1, y1 = r
        for y in range(y0, y1):
            for x in range(x0, x1):
                self.px[x, y] = tone(c, 1 + self.rng.uniform(-noise, noise))

    def put(self, x, y, c):
        if 0 <= x < self.tex and 0 <= y < self.tex:
            self.px[x, y] = tuple(c) if len(c) == 4 else tuple(c) + (255,)

    def save(self):
        tex_path = os.path.join(ASSETS, 'textures/item/%s.png' % self.name)
        self.im.save(tex_path)
        model = {'credit': 'Generated by tools/gen_props.py',
                 'textures': {'0': 'papon:item/' + self.name, 'particle': 'papon:item/' + self.name},
                 'elements': self.elements}
        if self.render_type:
            model['render_type'] = self.render_type
        if self.display:
            model['display'] = self.display
        path = os.path.join(ASSETS, 'models/item/%s.json' % self.name)
        with open(path, 'w', newline='\n') as f:
            json.dump(model, f, indent=1)
        return path


def solid(c, noise=0.06):
    return lambda f, r, m: m.fill(r, c, noise)


def spotted(c, spot, chance, noise=0.07):
    def p(f, r, m):
        m.fill(r, c, noise)
        x0, y0, x1, y1 = r
        for y in range(y0, y1):
            for x in range(x0, x1):
                if m.rng.random() < chance:
                    m.put(x, y, tone(spot, 1 + m.rng.uniform(-0.1, 0.1)))
    return p


# =========================================================== the tequila
GLASS = (226, 240, 232, 120)
GOLD = (226, 150, 34)
GOLD_LT = (250, 196, 76)
LABEL = (244, 234, 206)
AGAVE = (62, 128, 140)
WOOD = (176, 120, 70)
STAMP = (52, 132, 70)


def tequila():
    m = Model('tequila', 128, 1942)
    m.render_type = 'minecraft:translucent'

    def body(f, r, m):
        x0, y0, x1, y1 = r
        h = y1 - y0
        if f in ('up', 'down'):
            m.fill(r, GOLD if f == 'down' else (236, 246, 240, 150), 0.04)
            return
        for y in range(y0, y1):
            for x in range(x0, x1):
                t = (y - y0) / h
                c = (236, 246, 240, 150) if t < 0.07 else tone(GOLD, 0.82 + 0.35 * (1 - t))
                if x in (x0, x1 - 1) and t >= 0.07:
                    c = tone(c, 1.2)
                m.put(x, y, c)
        if f in ('north', 'south'):
            # the label: cream, a red band and the name up top, a blue agave fanning out of its heart
            lx0, lx1 = x0 + 1, x1 - 1
            ly0, ly1 = y0 + int(h * 0.28), y0 + int(h * 0.88)
            m.fill((lx0, ly0, lx1, ly1), LABEL, 0.03)
            for x in range(lx0, lx1):
                m.put(x, ly0, (178, 34, 30))
                m.put(x, ly0 + 1, (178, 34, 30))
                m.put(x, ly1 - 1, (196, 150, 52))
            for x in range(lx0 + 2, lx1 - 2):
                if (x - lx0) % 2 == 0:
                    m.put(x, ly0 + 3, (40, 30, 26))                      # T E Q U I L A
            cx, base = (lx0 + lx1) // 2, ly1 - 3
            for ang in (-70, -45, -22, 0, 22, 45, 70):
                ln = 5 if abs(ang) < 30 else 4
                for k in range(ln):
                    x = cx + round(math.sin(math.radians(ang)) * k)
                    y = base - round(math.cos(math.radians(ang)) * k)
                    m.put(x, y, tone(AGAVE, 1.1 if k == ln - 1 else 0.95))
            m.put(cx, base + 1, (90, 70, 40))
        if f == 'east':
            cx, cy = (x0 + x1) // 2, y0 + h // 2
            for dy in range(-1, 2):
                for dx in range(-1, 2):
                    m.put(cx + dx, cy + dy, (214, 172, 60) if dx or dy else (150, 40, 30))

    def glass(f, r, m):
        x0, y0, x1, y1 = r
        for y in range(y0, y1):
            for x in range(x0, x1):
                edge = x in (x0, x1 - 1)
                m.put(x, y, (236, 246, 240, 210) if edge else tone(GOLD_LT, 1.0, 200))

    def neck(f, r, m):
        x0, y0, x1, y1 = r
        for y in range(y0, y1):
            for x in range(x0, x1):
                m.put(x, y, (236, 246, 240, 220) if x in (x0, x1 - 1) else (200, 226, 214, 170))

    def cork(f, r, m):
        x0, y0, x1, y1 = r
        for y in range(y0, y1):
            for x in range(x0, x1):
                grain = 0.9 + 0.12 * math.sin((x * 1.7 + y * 0.4) * 1.3)
                m.put(x, y, tone(WOOD, grain + m.rng.uniform(-0.05, 0.05)))

    m.box([5, 0, 5], [11, 0.6, 11], solid((200, 220, 212, 230), 0.03), name='base')
    m.box([5, 0.6, 5], [11, 9, 11], body, name='body')
    m.box([4.6, 0.6, 5.4], [11.4, 8.9, 10.6], body, name='body_x')
    m.box([5.4, 0.6, 4.6], [10.6, 8.9, 11.4], body, name='body_z')
    m.box([5.6, 9, 5.6], [10.4, 9.8, 10.4], glass, name='shoulder')
    m.box([6.9, 9.8, 6.9], [9.1, 12.2, 9.1], neck, name='neck')
    m.box([6.6, 12.2, 6.6], [9.4, 12.6, 9.4], solid((40, 34, 30), 0.04), name='collar')
    m.box([6.2, 12.6, 6.2], [9.8, 15, 9.8], cork, name='cork')
    m.box([7.6, 11.8, 6.1], [8.4, 15.1, 9.9], solid(STAMP, 0.05), name='stamp')
    m.display = {
        'gui': {'rotation': [20, -35, 0], 'translation': [0, 0.5, 0], 'scale': [1.05, 1.05, 1.05]},
        'ground': {'translation': [0, 2, 0], 'scale': [0.55, 0.55, 0.55]},
        'fixed': {'translation': [0, 1, 0], 'scale': [1, 1, 1]},
        'head': {'translation': [0, 14, 0]},
        'thirdperson_righthand': {'translation': [0, 2.5, 1], 'scale': [0.6, 0.6, 0.6]},
        'thirdperson_lefthand': {'translation': [0, 2.5, 1], 'scale': [0.6, 0.6, 0.6]},
        'firstperson_righthand': {'rotation': [0, -20, 0], 'translation': [1, 3, 0], 'scale': [0.65, 0.65, 0.65]},
        'firstperson_lefthand': {'rotation': [0, -20, 0], 'translation': [1, 3, 0], 'scale': [0.65, 0.65, 0.65]},
    }
    return m.save()


