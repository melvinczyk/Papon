def save(im, rel):
    path = os.path.join(ASSETS, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path)
    return path


def save_json(obj, rel):
    path = os.path.join(ASSETS, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(obj, f, indent=2)
        f.write('\n')
    return path


def shade(c, k):
    return tuple(max(0, min(255, int(v * k))) for v in c[:3]) + (255,)


def coupon():
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(COUPON):
        for x, ch in enumerate(row.ljust(16, '.')[:16]):
            c = COUPON_PALETTE.get(ch)
            if c:
                im.putpixel((x, y), c)
    return save(im, 'textures/item/taco_coupon.png')


# ---------------------------------------------------------------- Jarritos
def jarrito_texture(liquid):
    """Layout: body sides 0..4 x 2..10, body ends 4..8 x 0..4, shoulder 8..11 x 0..2,
    neck 8..10 x 2..5, cap side 11..14 x 0..1, cap top 11..14 x 1..4."""
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = im.load()
    glass = (200, 232, 226)
    for y in range(2, 10):
        for x in range(0, 4):
            c = liquid
            if y == 2:
                c = glass                         # the air gap under the shoulder
            elif 5 <= y <= 7:
                c = (250, 250, 244)               # label
                if y == 6 and x in (1, 2):
                    c = shade(liquid, 0.65)[:3]   # the flavour band across the label
                if y == 5 and x == 1:
                    c = (24, 24, 24)              # the little logo
            k = 1.18 if x == 0 else (0.86 if x == 3 else 1.0)  # glass highlight / shadow
            px[x, y] = shade(c, k)
    for y in range(0, 4):
        for x in range(4, 8):
            px[x, y] = shade(liquid, 0.9 if (x + y) % 2 else 1.0)
    for y in range(0, 2):
        for x in range(8, 11):
            px[x, y] = shade(glass, 1.1 if x == 8 else 0.95)
    for y in range(2, 5):
        for x in range(8, 10):
            px[x, y] = shade(glass, 1.12 if x == 8 else 0.92)
    cap = (226, 196, 90)
    for x in range(11, 14):
        px[x, 0] = shade(cap, 0.85 if x % 2 else 1.05)  # crimped edge
        for y in range(1, 4):
            px[x, y] = shade(cap, 1.0 if (x + y) % 2 else 0.9)
    return im


def faces(side, end=None):
    f = {d: {'uv': side, 'texture': '#0'} for d in ('north', 'south', 'east', 'west')}
    if end:
        f['up'] = {'uv': end, 'texture': '#0'}
        f['down'] = {'uv': end, 'texture': '#0'}
    return f


