# ---------------------------------------------------------------- chancla
def chancla_texture():
    """Layout: sole top 0..10 x 0..14, sole edge 10..16 x 0..2, strap 10..16 x 2..4, tread 10..16 x 4..14."""
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = im.load()
    sole = (56, 112, 196)
    foot = (84, 142, 222)
    for y in range(0, 14):
        for x in range(0, 10):
            c = sole
            # a worn footprint where the foot goes
            if 1 <= x <= 8 and 2 <= y <= 12 and not (y > 9 and x in (1, 8)) and not (y < 4 and x in (1, 8)):
                c = foot
            px[x, y] = shade(c, 1.0 if (x + y) % 3 else 0.94)
    for x in range(10, 16):
        for y in range(0, 2):
            px[x, y] = shade(sole, 0.75)
        for y in range(2, 4):
            px[x, y] = shade((246, 246, 240), 1.0 if (x + y) % 2 else 0.92)
        for y in range(4, 14):
            px[x, y] = shade(sole, 0.6 if (x + y) % 2 else 0.7)  # tread
    return im


