# ---------------------------------------------------------------- snooze particle
SNOOZE = [
    "WWWWWWW.",
    "WbbbbbW.",
    "....bW..",
    "...bW...",
    "..bW....",
    ".bW.....",
    "WWWWWWW.",
    "bbbbbbb.",
]


def snooze():
    im = Image.new('RGBA', (8, 8), (0, 0, 0, 0))
    for y, row in enumerate(SNOOZE):
        for x, ch in enumerate(row):
            if ch == 'W':
                im.putpixel((x, y), (250, 250, 255, 255))
            elif ch == 'b':
                im.putpixel((x, y), (110, 140, 220, 255))
    save(im, 'textures/particle/snooze.png')
    return save_json({'textures': ['papon:snooze']}, 'particles/snooze.json')


def main():
    print(coupon())
    for name, liquid in FLAVOURS.items():
        item = 'jarrito_' + name
        print(save(jarrito_texture(liquid), 'textures/item/%s.png' % item))
        print(save_json(jarrito_model(item), 'models/item/%s.json' % item))
    print(save(chancla_texture(), 'textures/item/chancla.png'))
    print(save_json(chancla_model(), 'models/item/chancla.json'))
    print(snooze())


if __name__ == '__main__':
    main()
